import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import test from "node:test";
import yaml from "js-yaml";

import {
  BLOCKED_CHECKOUT_REFUND_RECOVERY_MIGRATION,
  blockedCheckoutRefundRecoveryDefinitions,
  buildBlockedCheckoutRefundRecoveryMigration,
  functionBodyMd5,
} from "../scripts/build-blocked-checkout-refund-recovery-migration.mjs";

const migrationPath =
  process.env.BLOCKED_CHECKOUT_REFUND_RECOVERY_MIGRATION_PATH ||
  `prisma/migrations/${BLOCKED_CHECKOUT_REFUND_RECOVERY_MIGRATION}/migration.sql`;
const migration = fs.readFileSync(migrationPath, "utf8");
const workflow = fs.readFileSync(
  ".github/workflows/blocked-checkout-refund-recovery-production.yml",
  "utf8",
);
const parsedWorkflow = yaml.load(workflow, { schema: yaml.JSON_SCHEMA });
const bindingScript = parsedWorkflow.jobs.apply.steps.find(
  (step) => step.name === "Bind release to exact main and completed push workflows",
).with.script;
const AsyncFunction = Object.getPrototypeOf(async function () {}).constructor;

async function runBindingScript({ failingPath, omitPath } = {}) {
  const releaseSha = "a".repeat(40);
  const workflowRunId = 101;
  const runs = [
    [201, "CI", ".github/workflows/ci.yml"],
    [202, "Account deletion", ".github/workflows/account-deletion-worker-bootstrap-proof.yml"],
    [203, "Order staff", ".github/workflows/order-staff-bootstrap-proof.yml"],
    [204, "Paid repair", ".github/workflows/order-paid-repair-lock-proof.yml"],
    [205, "Deletion race", ".github/workflows/order-account-deletion-concurrency-proof.yml"],
  ].map(([id, name, path]) => ({
    id,
    name,
    path,
    event: "push",
    head_branch: "main",
    head_sha: releaseSha,
    status: "completed",
    conclusion: path === failingPath ? "failure" : "success",
  })).filter((run) => run.path !== omitPath);
  const listWorkflowRunsForRepo = () => {};
  const github = {
    rest: {
      repos: {
        getBranch: async () => ({ data: { commit: { sha: releaseSha } } }),
      },
      actions: {
        getWorkflowRun: async () => ({
          data: {
            name: "CI",
            event: "push",
            head_branch: "main",
            head_sha: releaseSha,
            status: "completed",
            conclusion: "success",
          },
        }),
        listWorkflowRunsForRepo,
      },
    },
    paginate: async (method) => {
      assert.equal(method, listWorkflowRunsForRepo);
      return runs;
    },
  };
  const context = { sha: releaseSha, repo: { owner: "test", repo: "grainline" } };
  const processStub = {
    env: {
      REVIEWED_RELEASE_COMMIT: releaseSha,
      REVIEWED_MAIN_CI_RUN_ID: String(workflowRunId),
    },
  };
  await new AsyncFunction("github", "context", "process", bindingScript)(
    github,
    context,
    processStub,
  );
}

test("#688 migration is generated byte-for-byte from its two live predecessors", () => {
  assert.equal(buildBlockedCheckoutRefundRecoveryMigration(), migration);
  assert.equal(
    createHash("sha256").update(migration).digest("hex"),
    "e2cfb6668d4ec075e0317916be851b5c304f8f7d70ffe2865da5040f578a05d0",
  );

  const definitions = blockedCheckoutRefundRecoveryDefinitions();
  assert.deepEqual(
    {
      checkoutBefore: functionBodyMd5(definitions.checkoutPredecessor),
      checkoutAfter: functionBodyMd5(definitions.checkoutSuccessor),
      reconciliationBefore: functionBodyMd5(
        definitions.reconciliationPredecessor,
      ),
      reconciliationAfter: functionBodyMd5(
        definitions.reconciliationSuccessor,
      ),
    },
    {
      checkoutBefore: "4bd7580c27318ff118ea9640c3dd72b0",
      checkoutAfter: "c11a02db980fdda7a9d57bf67f5d8628",
      reconciliationBefore: "fb4e95894e189462ff2a1d8f953c248d",
      reconciliationAfter: "64f4a2c7f9abfe7b30bc3365c1db38f6",
    },
  );
});

test("#688 changes only exact claim recovery and immutable ADMIN reconciliation", () => {
  const definitions = blockedCheckoutRefundRecoveryDefinitions();
  assert.match(
    definitions.checkoutSuccessor,
    /paymentRefundBlocked[\s\S]*refundClaimProviderAuthorizedAt[\s\S]*outcome := 'retry'/u,
  );
  assert.match(
    definitions.reconciliationSuccessor,
    /claimGeneration"[\s\S]*> source_reconciliation\."claimSourceGeneration"[\s\S]*refundClaimSourceGeneration" = locked_event\."claimGeneration"/u,
  );
  assert.match(
    definitions.reconciliationSuccessor,
    /grainline_blocked_checkout_refund_record_core\(\s*locked_event\.id,\s*locked_event\."claimGeneration"/u,
  );
  assert.doesNotMatch(migration, /(?:ALTER|CREATE|DROP) TABLE|CREATE POLICY/u);
  assert.doesNotMatch(migration, /stripe\.(?:refunds|charges|transfers)/iu);
  assert.equal(
    (migration.match(/CREATE OR REPLACE FUNCTION public\./gu) ?? []).length,
    2,
  );
});

test("a processed Stripe event cannot acquire a later claim generation", () => {
  const source = fs.readFileSync(
    "prisma/migrations/20260805012000_prepare_order_payment_shipping_compatibility/migration.sql",
    "utf8",
  );
  const processed = source.indexOf('IF source_event."processedAt" IS NOT NULL THEN');
  const increment = source.indexOf(
    'SET "claimGeneration" = event."claimGeneration" + 1',
    processed,
  );
  assert.ok(processed >= 0 && increment > processed);
  assert.match(
    source.slice(processed, increment),
    /RETURN QUERY[\s\S]*SELECT 'processed'::text[\s\S]*RETURN;/u,
  );
});

test("Production workflow binds one migration to exact main and every green push workflow", async () => {
  assert.ok(parsedWorkflow.on.workflow_dispatch);
  assert.equal(parsedWorkflow.permissions.actions, "read");
  assert.equal(parsedWorkflow.permissions.contents, "read");
  assert.equal(parsedWorkflow.concurrency.group, "production-database-migrations");
  assert.equal(parsedWorkflow.concurrency["cancel-in-progress"], false);
  assert.equal(parsedWorkflow.jobs.apply.environment, "Production");
  await assert.doesNotReject(runBindingScript());
  await assert.rejects(
    runBindingScript({
      failingPath: ".github/workflows/order-paid-repair-lock-proof.yml",
    }),
    /Exact-main push workflows are not all green/u,
  );
  await assert.rejects(
    runBindingScript({
      omitPath: ".github/workflows/order-staff-bootstrap-proof.yml",
    }),
    /Required exact-main push workflows are absent/u,
  );
});

test("Production workflow pins the exact reviewed migration bytes", () => {
  const verifyBytesStep = parsedWorkflow.jobs.apply.steps.find(
    (step) => step.name === "Verify exact candidate bytes and focused behavior",
  );
  const pinnedDigest = verifyBytesStep.run.match(
    /echo "([0-9a-f]{64})  prisma\/migrations\/\$migration\/migration\.sql"/u,
  )?.[1];
  assert.equal(
    pinnedDigest,
    createHash("sha256").update(migration).digest("hex"),
  );
});

test("Production workflow is restart-safe, database-only, and postflights exact state", () => {
  assert.match(
    workflow,
    /inputs\.confirmation == 'apply-reviewed-blocked-checkout-refund-recovery'/u,
  );
  assert.match(workflow, /github\.ref == 'refs\/heads\/main'/u);
  assert.match(workflow, /github\.run_attempt == 1/u);
  assert.match(
    workflow,
    /REVIEWED_PENDING_MIGRATIONS="\$migration"[\s\S]*assert-reviewed-pending-migrations/u,
  );
  assert.equal((workflow.match(/\bnpx prisma migrate deploy\b/gu) ?? []).length, 1);
  assert.match(
    workflow,
    /blocked-checkout-refund-recovery-production-verify\.mjs[\s\S]*preflight/u,
  );
  assert.match(
    workflow,
    /blocked-checkout-refund-recovery-production-verify\.mjs[\s\S]*postflight/u,
  );
  assert.doesNotMatch(workflow, /vercel\s+(?:deploy|alias|promote)/iu);
  assert.doesNotMatch(workflow, /stripe\s+(?:refunds|charges|transfers)/iu);
  const checked = spawnSync(
    process.execPath,
    ["--check", "scripts/blocked-checkout-refund-recovery-production-verify.mjs"],
    { encoding: "utf8" },
  );
  assert.equal(checked.status, 0, checked.stderr);
});
