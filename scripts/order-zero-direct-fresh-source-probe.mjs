// Read-only child-process probe, not a release executor. Only the fixed source
// fence is imported; npm dependencies, database and migration code stay unloaded.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const KEYS = ["nodeSha256", "nodeVersion", "releaseCommit", "sourceCatalogSha256", "sourceFenceSha256"];
const hash = bytes => createHash("sha256").update(bytes).digest("hex");
const FAILURE = "Order fresh source probe failed; no execution admission";
const BOOTSTRAP = `
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {pathToFileURL} from 'node:url';
try {
  const reviewed = JSON.parse(process.argv[1]);
  const hash = bytes => createHash('sha256').update(bytes).digest('hex');
  const allowedEnv = ['LANG','LC_ALL','PATH','TZ'];
  // macOS adds its text-encoding descriptor even to an explicitly empty spawn
  // environment. It is not a loader, credential or module-resolution setting.
  if (process.platform === 'darwin' && process.env.__CF_USER_TEXT_ENCODING !== undefined) {
    assert.match(process.env.__CF_USER_TEXT_ENCODING, /^0x[0-9a-f]+:0x[0-9a-f]+:0x[0-9a-f]+$/i);
    allowedEnv.push('__CF_USER_TEXT_ENCODING');
  }
  assert.deepEqual(Object.keys(process.env).sort(), allowedEnv.sort());
  assert.equal(process.version, reviewed.nodeVersion);
  assert.equal(hash(fs.readFileSync(process.execPath)), reviewed.nodeSha256);
  const root = process.cwd();
  assert.equal(fs.realpathSync(root), root);
  const file = path.join(root, 'scripts/order-zero-direct-release-source.mjs');
  assert.equal(fs.realpathSync(file), file);
  const stat = fs.lstatSync(file);
  assert.ok(stat.isFile() && stat.nlink === 1 && stat.size <= 1024 * 1024);
  assert.equal(hash(fs.readFileSync(file)), reviewed.sourceFenceSha256);
  // No repository module was imported before the fixed fence byte check.
  const {createOrderZeroDirectSourceFence} = await import(pathToFileURL(file).href);
  const fence = createOrderZeroDirectSourceFence(root, reviewed.releaseCommit);
  const source = fence.capture();
  assert.equal(source.catalogSha256, reviewed.sourceCatalogSha256);
  fence.verify(source);
  assert.equal(hash(fs.readFileSync(file)), reviewed.sourceFenceSha256);
  process.stdout.write(JSON.stringify({releaseCommit: reviewed.releaseCommit,
    sourceCatalogSha256: source.catalogSha256, nodeVersion: process.version,
    childPid: process.pid, trackedFileCount: source.fileCount}));
} catch { process.stderr.write('${FAILURE}'); process.exitCode = 1; }
`;

// Reviewed pins must come from an accepted release/toolchain artifact, not be
// generated by a production entrypoint from whatever happens to be installed.
export function probeOrderZeroDirectFreshSource({ directory, reviewed: input }) {
  try {
    const reviewed = structuredClone(input);
    assert.deepEqual(Object.keys(reviewed).sort(), KEYS);
    assert.ok(typeof reviewed.releaseCommit === "string" && /^[a-f0-9]{40}$/u.test(reviewed.releaseCommit));
    for (const key of ["nodeSha256", "sourceCatalogSha256", "sourceFenceSha256"]) assert.ok(typeof reviewed[key] === "string" && /^[a-f0-9]{64}$/u.test(reviewed[key]));
    assert.ok(typeof reviewed.nodeVersion === "string" && /^v22\.\d+\.\d+$/u.test(reviewed.nodeVersion));
    assert.equal(process.version, reviewed.nodeVersion);
    assert.ok(typeof directory === "string" && path.isAbsolute(directory) && path.resolve(directory) === directory && fs.realpathSync(directory) === directory);
    const node = fs.realpathSync(process.execPath);
    assert.equal(hash(fs.readFileSync(node)), reviewed.nodeSha256);
    const raw = execFileSync(node, ["--input-type=module", "--eval", BOOTSTRAP, JSON.stringify(reviewed)], {
      cwd: directory, encoding: "utf8", timeout: 20000, maxBuffer: 16384,
      stdio: ["ignore", "pipe", "pipe"], env: { PATH: "/usr/bin:/bin", TZ: "UTC", LANG: "C", LC_ALL: "C" },
    });
    const result = JSON.parse(raw);
    assert.deepEqual(Object.keys(result).sort(), ["childPid", "nodeVersion", "releaseCommit", "sourceCatalogSha256", "trackedFileCount"]);
    assert.ok(result.releaseCommit === reviewed.releaseCommit && result.sourceCatalogSha256 === reviewed.sourceCatalogSha256 && result.nodeVersion === reviewed.nodeVersion);
    assert.ok(Number.isSafeInteger(result.childPid) && result.childPid > 0 && result.childPid !== process.pid);
    assert.ok(Number.isSafeInteger(result.trackedFileCount) && result.trackedFileCount > 0 && result.trackedFileCount <= 10000);
    assert.equal(hash(fs.readFileSync(node)), reviewed.nodeSha256);
    return Object.freeze({ ...result, freshSourceProbePassed: true, loadedReleaseGraphProven: false,
      installedToolchainProven: false, completeProductionScope: false, productionExecutionAuthorized: false });
  } catch { throw new Error(FAILURE); }
}
