// Dormant filesystem boundary only: no credentials, database connections,
// workflow dispatch, Prisma invocation, or production execution authority.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createOrderZeroDirectReleaseScope } from "./order-zero-direct-release-scope.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LOCK = Buffer.from('# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n');
const hash = bytes => createHash("sha256").update(bytes).digest("hex");
const exact = (actual, expected) => assert.deepEqual(actual, expected, "selected migration file inventory drifted");

function directory(target, mode) {
  assert.equal(path.resolve(target), fs.realpathSync(target), "noncanonical directory or symlink ancestor");
  const stat = fs.lstatSync(target);
  assert.ok(stat.isDirectory() && !stat.isSymbolicLink(), "expected a real directory");
  if (mode !== undefined) {
    assert.equal(stat.uid, process.getuid(), "artifact directory owner drifted");
    assert.equal(stat.mode & 0o777, mode, "artifact directory mode drifted");
  }
}

function readRegular(target, checksum, mode) {
  assert.ok(Number.isInteger(fs.constants.O_NOFOLLOW) && Number.isInteger(fs.constants.O_NONBLOCK), "safe descriptor reads unavailable");
  const fd = fs.openSync(target, fs.constants.O_RDONLY | fs.constants.O_NOFOLLOW | fs.constants.O_NONBLOCK);
  try {
    const before = fs.fstatSync(fd, { bigint: true });
    assert.ok(before.isFile() && before.nlink === 1n, "migration file must be regular and not hard-linked");
    assert.ok(before.size <= 16n * 1024n * 1024n, "migration file exceeds bounded read size");
    if (mode !== undefined) {
      assert.equal(before.uid, BigInt(process.getuid()), "artifact file owner drifted");
      assert.equal(before.mode & 0o777n, BigInt(mode), "artifact file mode drifted");
    }
    const bytes = fs.readFileSync(fd);
    const after = fs.fstatSync(fd, { bigint: true });
    const named = fs.lstatSync(target, { bigint: true });
    assert.ok(!named.isSymbolicLink(), "migration path became a symlink");
    for (const key of ["dev", "ino", "size", "mtimeNs", "ctimeNs", "nlink"]) {
      assert.equal(after[key], before[key], "migration changed during read");
      assert.equal(named[key], before[key], "migration path changed during read");
    }
    assert.equal(hash(bytes), checksum, "selected migration checksum drifted");
    return bytes;
  } finally { fs.closeSync(fd); }
}

// The catalog comes from the existing byte-pinned release reader, never from
// the directory being inspected or an arbitrary caller-provided allowlist.
export function createOrderZeroDirectFileFence({ sourceRoot = ROOT } = {}) {
  assert.equal(fs.realpathSync(process.cwd()), ROOT, "release reader requires its repository working directory");
  const scope = createOrderZeroDirectReleaseScope();
  const entries = [...scope.manifest.base, ...scope.manifest.members];
  const names = entries.map(row => row.migration_name);
  const source = path.resolve(sourceRoot, "prisma/migrations");
  const handles = new WeakMap();

  function readTree(root, staged = false) {
    directory(root, staged ? 0o500 : undefined);
    exact(fs.readdirSync(root).sort(), [...names, "migration_lock.toml"].sort());
    const files = new Map([["migration_lock.toml", readRegular(path.join(root, "migration_lock.toml"), hash(LOCK), staged ? 0o400 : undefined)]]);
    for (const entry of entries) {
      const folder = path.join(root, entry.migration_name);
      directory(folder, staged ? 0o500 : undefined);
      exact(fs.readdirSync(folder), ["migration.sql"]);
      const relative = `${entry.migration_name}/migration.sql`;
      files.set(relative, readRegular(path.join(root, relative), entry.checksum, staged ? 0o400 : undefined));
    }
    return files;
  }

  function verify(handle) {
    const state = handles.get(handle);
    assert.ok(state, "artifact is not owned by this file fence");
    directory(state.parent, 0o700);
    readTree(source);
    readTree(state.root, true);
    return handle;
  }

  function stage(ledgerRows, parent) {
    // This only classifies supplied observations. A future serialized runner
    // must obtain a fresh audited database snapshot; this is not that proof.
    const selected = scope.classify(ledgerRows, "restart");
    directory(parent, 0o700);
    const sourceRootPath = fs.realpathSync(sourceRoot);
    const relative = path.relative(sourceRootPath, path.resolve(parent));
    assert.ok(relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative), "artifact parent must be outside source tree");
    const files = readTree(source);
    const root = fs.mkdtempSync(path.join(parent, "order-prefix-"));
    fs.chmodSync(root, 0o700);
    // On failure leave the exact private partial artifact for inspection. No
    // recursive deletion and no recovery by overwriting a previous artifact.
    for (const name of names) fs.mkdirSync(path.join(root, name), { mode: 0o700 });
    for (const [relativePath, bytes] of files) {
      const fd = fs.openSync(path.join(root, relativePath), "wx", 0o400);
      try { fs.writeFileSync(fd, bytes); fs.fsyncSync(fd); } finally { fs.closeSync(fd); }
    }
    for (const name of names) fs.chmodSync(path.join(root, name), 0o500);
    fs.chmodSync(root, 0o500);
    const handle = Object.freeze({ directory: root, prefixLength: selected.prefixLength,
      fileCount: files.size, sourceCatalogSha256: scope.manifest.sourceCatalogSha256,
      remainingMigrations: Object.freeze(selected.remainingMigrations.map(row => row.migration_name)),
      freshDatabaseScopeProven: false, loadedSourceAndCiProven: false,
      completeProductionScope: false, productionExecutionAuthorized: false });
    handles.set(handle, { root, parent });
    verify(handle);
    return handle;
  }

  return Object.freeze({ stage, verify });
}
