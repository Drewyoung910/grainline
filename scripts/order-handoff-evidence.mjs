// Inactive, read-only collector. Validate every input before creating an export.
// No raw process output, channel capability, environment, home/cache/tmp or DB rows.
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { pathToFileURL } from "node:url";
import { FLAGS, hash, keys, id, sha, uuid, directoryGuard, readBounded, readJson, validatePlan, assertPreparationEnvironment } from "./order-handoff-common.mjs";

const PHASES = ["preparing", "awaiting-handoff", "loading", "executing", "complete", "failed"];
const STAGES = ["prepared", "apply-intent", "prefix-verified", "grant-intent", "grants-verified", "status-verified", "audit-verified", "complete"];
const FINAL_MEMBER = "20260905170000_correct_order_authority_composition";
const LOCK = Buffer.from('# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n');
const STATE_KEYS = ["version", "phase", "supervisorPid", "workerPid", "sessionId", "releaseCommit", "runId", "runAttempt", ...Object.keys(FLAGS)];
function phase(value, plan) {
  assert.equal(value.version, 1); assert.ok(PHASES.includes(value.phase));
  assert.ok(Number.isSafeInteger(value.supervisorPid) && value.supervisorPid > 0);
  assert.ok(value.workerPid === null || Number.isSafeInteger(value.workerPid) && value.workerPid > 0);
  if (value.sessionId !== null) uuid(value.sessionId);
  for (const key of ["releaseCommit", "runId", "runAttempt"]) assert.equal(value[key], plan.context[key]);
  for (const [key, expected] of Object.entries(FLAGS)) assert.equal(value[key], expected);
  return Object.fromEntries(STATE_KEYS.map(key => [key, value[key]]));
}
function execution(value) {
  keys(value, ["status", "initialPrefix", "finalPrefix", "appliedMemberCount", "reviewedFunctionCount", "migrationStatusVerified", "globalAuthorityVerified", "finalReadOnlyScopeVerified", ...Object.keys(FLAGS)]);
  assert.equal(value.status, "passed"); assert.equal(value.finalPrefix, 17);
  assert.ok(Number.isInteger(value.initialPrefix) && value.initialPrefix >= 0 && value.initialPrefix <= 17);
  assert.equal(value.appliedMemberCount, 17 - value.initialPrefix); assert.equal(value.reviewedFunctionCount, 36);
  for (const key of ["migrationStatusVerified", "globalAuthorityVerified", "finalReadOnlyScopeVerified"]) assert.equal(value[key], true);
  for (const [key, expected] of Object.entries(FLAGS)) assert.equal(value[key], expected);
}
function journal(value, plan) {
  keys(value, ["version", "attemptId", "releaseCommit", "sourceCatalogSha256", "initialPrefix", "prefixCatalogSha256", "stage", "productionExecutionAuthorized"]);
  assert.equal(value.version, 1); uuid(value.attemptId);
  assert.equal(value.releaseCommit, plan.reviewed.releaseCommit); assert.equal(value.sourceCatalogSha256, plan.reviewed.sourceCatalogSha256);
  sha(value.prefixCatalogSha256); assert.ok(Number.isInteger(value.initialPrefix) && value.initialPrefix >= 0 && value.initialPrefix <= 17);
  assert.ok(STAGES.includes(value.stage)); assert.equal(value.productionExecutionAuthorized, false);
}
function stagedDirectory(target) {
  assert.equal(fs.realpathSync(target), target);
  const s = fs.lstatSync(target); assert.ok(s.isDirectory() && s.uid === process.getuid() && [0o500, 0o700].includes(s.mode & 0o7777));
  return s.mode & 0o7777;
}
function absentProcess(pid) {
  if (pid === null) return;
  try { process.kill(pid, 0); } catch (error) { assert.equal(error.code, "ESRCH"); return; }
  // An unreaped zombie cannot mutate artifacts; all other live PIDs block collection.
  const state = execFileSync("/bin/ps", ["-o", "stat=", "-p", String(pid)], { encoding: "utf8", timeout: 1000,
    env: { PATH: "/usr/bin:/bin" }, stdio: ["ignore", "pipe", "pipe"] }).trim();
  assert.ok(state.startsWith("Z"));
}
export async function collectOrderHandoffEvidence({ channel, output }) {
  try {
    assertPreparationEnvironment(); const checkChannel = directoryGuard(channel);
    const plan = validatePlan(readJson(path.join(channel, "plan.json")));
    const fencePath = path.join(plan.directory, "scripts/order-zero-direct-release-source.mjs");
    assert.equal(hash(readBounded(fencePath, 1024 * 1024, fs.lstatSync(fencePath).mode & 0o7777)), plan.reviewed.sourceFenceSha256);
    const { createOrderZeroDirectSourceFence } = await import(pathToFileURL(fencePath).href);
    const fence = createOrderZeroDirectSourceFence(plan.directory, plan.reviewed.releaseCommit), source = fence.capture();
    assert.equal(source.catalogSha256, plan.reviewed.sourceCatalogSha256);
    const collected = new Map(), checks = []; let total = 0;
    const add = (name, bytes) => {
      assert.ok(!collected.has(name)); bytes = Buffer.from(bytes); total += bytes.length;
      assert.ok(total <= 32 * 1024 * 1024); collected.set(name, bytes);
    };
    const json = (name, value) => add(name, JSON.stringify(value) + "\n");
    const read = (file, mode = 0o600, limit = 16384) => {
      const bytes = readBounded(file, limit, mode), digest = hash(bytes);
      checks.push(() => assert.equal(hash(readBounded(file, limit, mode)), digest)); return bytes;
    };
    const channelNames = fs.readdirSync(channel).sort();
    assert.ok(channelNames.every(name => /^(?:plan\.json|launch\.json|ready\.json|capability|handoff\.sock|result\.json|phase-[0-5]\.json)$/u.test(name)));
    const launch = JSON.parse(read(path.join(channel, "launch.json")));
    keys(launch, ["version", "supervisorPid", "releaseCommit", "runId", "runAttempt", ...Object.keys(FLAGS)]);
    const initial = { ...launch, workerPid: null, sessionId: null, phase: "preparing" }; phase(initial, plan); json("supervisor/launch.json", launch);
    const names = channelNames.filter(name => /^phase-/u.test(name)); assert.ok(names.length <= 6);
    const phases = names.map((name, i) => { assert.equal(name, `phase-${i}.json`); const value = JSON.parse(read(path.join(channel, name))); keys(value, STATE_KEYS); phase(value, plan); json(`supervisor/${name}`, value); return value; });
    if (phases.length) { assert.equal(phases[0].phase, "preparing"); assert.equal(phases[0].supervisorPid, launch.supervisorPid); }
    for (let i = 1; i < phases.length; i++) {
      assert.ok(!["complete", "failed"].includes(phases[i - 1].phase));
      assert.ok(phases[i].phase === "failed" || PHASES.indexOf(phases[i].phase) === PHASES.indexOf(phases[i - 1].phase) + 1);
      assert.equal(phases[i].supervisorPid, phases[0].supervisorPid);
      if (phases[i - 1].workerPid !== null) assert.equal(phases[i].workerPid, phases[i - 1].workerPid);
      if (phases[i - 1].sessionId !== null) assert.equal(phases[i].sessionId, phases[i - 1].sessionId);
    }
    const last = phases.at(-1) ?? initial; absentProcess(last.supervisorPid); absentProcess(last.workerPid);
    let result;
    if (channelNames.includes("result.json")) {
      result = JSON.parse(read(path.join(channel, "result.json")));
      keys(result, [...STATE_KEYS, "outcome", "lastActivePhase", "operation", "failureCode", "requestedJobId", "evidenceUploadProven", "hostLossDurabilityProven", ...(result.outcome === "passed" ? ["execution"] : [])]);
      assert.deepEqual(phase(result, plan), last);
      assert.ok(["passed", "failed"].includes(result.outcome)); assert.equal(result.phase, result.outcome === "passed" ? "complete" : "failed");
      assert.equal(result.lastActivePhase, phases.at(-2)?.phase);
      assert.ok(["worker-start", "worker-prepare", "prepared-identity", "socket-listen", "handoff"].includes(result.operation));
      assert.ok([null, "EPERM", "EACCES", "EADDRINUSE", "ENOENT"].includes(result.failureCode));
      if (result.requestedJobId !== null) id(result.requestedJobId);
      assert.equal(result.evidenceUploadProven, false); assert.equal(result.hostLossDurabilityProven, false);
      if (result.outcome === "passed") { id(result.requestedJobId); execution(result.execution); }
      json("supervisor/result.json", result);
    }
    // Read no private channel capability/ready payload. Neither is an artifact.
    const claim = path.join(path.dirname(plan.directory), `.order-release-${path.basename(plan.directory)}`);
    let claimPresent = false, hostClaimPresent = false, selectedFiles = 0, artifactComplete = false, journalComplete = false, capsuleComplete = false, workerComplete = false;
    const hostClaim = path.join(fs.realpathSync("/tmp"), `grainline-order-admission-${process.getuid()}-${plan.context.runId}-${plan.context.runAttempt}`);
    if (fs.existsSync(hostClaim)) { const check = directoryGuard(hostClaim); check(); assert.deepEqual(fs.readdirSync(hostClaim), []); checks.push(check); hostClaimPresent = true; }
    if (fs.existsSync(claim)) {
      const check = directoryGuard(claim); check(); checks.push(check); claimPresent = true;
      const checkpoints = fs.readdirSync(claim).filter(name => name.startsWith("checkpoint-")).sort(); assert.ok(checkpoints.length <= 32);
      for (const name of checkpoints) {
        const match = /^checkpoint-([1-9][0-9]{0,5})-(preparing|installed|prepared|executing-admitted|admitted-complete|failed)-(disk-guard|install|engine-download|client-generation|generated-identity|complete|graph-import)\.json$/u.exec(name); assert.ok(match);
        const value = JSON.parse(read(path.join(claim, name)));
        keys(value, ["workerPid", "sessionId", "state", "loadedReleaseGraphProven", "installedToolchainProven", "preparationStage", "releaseCommit", ...Object.keys(FLAGS)]);
        assert.ok(Number.isSafeInteger(value.workerPid) && value.workerPid > 0); absentProcess(value.workerPid); uuid(value.sessionId);
        if (last.workerPid !== null) assert.equal(value.workerPid, last.workerPid);
        if (last.sessionId !== null) assert.equal(value.sessionId, last.sessionId);
        assert.equal(value.state, match[2]); assert.equal(value.preparationStage, match[3]); assert.equal(value.releaseCommit, plan.reviewed.releaseCommit);
        for (const key of ["loadedReleaseGraphProven", "installedToolchainProven"]) assert.equal(typeof value[key], "boolean");
        for (const [key, expected] of Object.entries(FLAGS)) assert.equal(value[key], expected);
        if (value.state === "admitted-complete") { assert.equal(value.loadedReleaseGraphProven, true); assert.equal(value.installedToolchainProven, true); workerComplete = true; }
        json(`worker/${name}`, value);
      }
      const artifacts = path.join(claim, "artifacts"), checkArtifacts = directoryGuard(artifacts); checks.push(checkArtifacts);
      const entries = fs.readdirSync(artifacts).sort();
      assert.ok(entries.length <= 3 && entries.every(name => /^(?:execution-journal|execution-capsule|order-prefix)-[A-Za-z0-9]{6}$/u.test(name)));
      const one = prefix => { const found = entries.filter(n => n.startsWith(prefix)); assert.ok(found.length <= 1); return found[0]; };
      const selected = one("order-prefix-"), capsule = one("execution-capsule-"), journalName = one("execution-journal-");
      if (selected) {
        const git = args => execFileSync("/usr/bin/git", ["-c", "core.fsmonitor=false", "-c", "core.hooksPath=/dev/null", ...args], { cwd: plan.directory, encoding: "utf8", timeout: 10000, maxBuffer: 4 * 1024 * 1024, stdio: ["ignore", "pipe", "pipe"],
          env: { PATH: "/usr/bin:/bin", GIT_CONFIG_NOSYSTEM: "1", GIT_CONFIG_GLOBAL: "/dev/null", GIT_NO_REPLACE_OBJECTS: "1", GIT_OPTIONAL_LOCKS: "0" } });
        const expected = git(["ls-tree", "--name-only", `${plan.reviewed.releaseCommit}:prisma/migrations`]).trim().split("\n")
          .filter(name => /^\d{14}_[a-z0-9_]+$/u.test(name) && name <= FINAL_MEMBER).sort();
        assert.equal(expected.length, 251); assert.equal(expected.at(-1), FINAL_MEMBER);
        const root = path.join(artifacts, selected), rootMode = stagedDirectory(root), actual = fs.readdirSync(root).sort();
        assert.ok(actual.every(name => name === "migration_lock.toml" || expected.includes(name)));
        let immutable = rootMode === 0o500;
        for (const name of actual) {
          if (name === "migration_lock.toml") { const bytes = read(path.join(root, name), 0o400); assert.deepEqual(bytes, LOCK); add(`selected/${name}`, bytes); selectedFiles++; continue; }
          const folder = path.join(root, name); immutable &&= stagedDirectory(folder) === 0o500;
          // Always validate directory identity, even if a preceding mode was incomplete.
          stagedDirectory(folder); const files = fs.readdirSync(folder); assert.ok(files.length <= 1 && files.every(n => n === "migration.sql"));
          if (files.length) {
            const relative = `${name}/migration.sql`, bytes = read(path.join(root, relative), 0o400, 16 * 1024 * 1024);
            const sourceFile = path.join(plan.directory, "prisma/migrations", relative);
            assert.equal(hash(bytes), hash(readBounded(sourceFile, 16 * 1024 * 1024, fs.lstatSync(sourceFile).mode & 0o7777)));
            add(`selected/${relative}`, bytes); selectedFiles++;
          }
        }
        artifactComplete = selectedFiles === 252 && immutable;
      }
      if (capsule) {
        assert.ok(selected); const root = path.join(artifacts, capsule), mode = stagedDirectory(root);
        const files = fs.readdirSync(root); assert.ok(files.length <= 1 && files.every(n => n === "prisma.config.mjs"));
        if (files.length) {
          const expected = `export default ${JSON.stringify({ schema: path.join(plan.directory, "prisma/schema.prisma"), migrations: { path: path.join(artifacts, selected) } }).slice(0, -1)},datasource:{url:process.env.DIRECT_URL}};\n`;
          const bytes = read(path.join(root, files[0]), 0o400); assert.equal(bytes.toString(), expected); add("capsule/prisma.config.mjs", bytes);
          capsuleComplete = mode === 0o500;
        }
      }
      if (journalName) {
        const root = path.join(artifacts, journalName), checkJournal = directoryGuard(root); checks.push(checkJournal);
        const files = fs.readdirSync(root); assert.ok(files.length <= 3 && files.every(n => ["execution.json", "execution.pending", "execution.lock"].includes(n)));
        let attemptId, state;
        for (const name of ["execution.json", "execution.pending"]) if (files.includes(name)) {
          const value = JSON.parse(read(path.join(root, name))); journal(value, plan);
          if (attemptId) assert.equal(value.attemptId, attemptId); attemptId = value.attemptId;
          if (name === "execution.json") state = value; json(`journal/${name}`, value);
        }
        if (files.includes("execution.lock")) { const lock = read(path.join(root, "execution.lock")).toString(); uuid(lock); if (attemptId) assert.equal(lock, attemptId); add("journal/execution.lock", lock); }
        journalComplete = state?.stage === "complete" && !files.includes("execution.pending") && !files.includes("execution.lock");
      }
      checks.push(() => { checkArtifacts(); assert.deepEqual(fs.readdirSync(artifacts).sort(), entries); });
    }
    // A passed supervisor record is insufficient without its complete artifacts.
    const outcome = result?.outcome === "passed" && artifactComplete && journalComplete && capsuleComplete && workerComplete && hostClaimPresent ? "passed" : result?.outcome === "failed" ? "failed" : "incomplete";
    json("binding.json", { version: 1, releaseCommit: plan.reviewed.releaseCommit, sourceCatalogSha256: plan.reviewed.sourceCatalogSha256,
      sourceFenceSha256: plan.reviewed.sourceFenceSha256, nodeSha256: plan.reviewed.nodeSha256, nodeVersion: plan.reviewed.nodeVersion,
      npmCliSha256: plan.reviewed.npmCliSha256, npmVersion: plan.reviewed.npmVersion, ci: plan.ci,
      runId: plan.context.runId, runAttempt: plan.context.runAttempt, requestedJobId: result?.requestedJobId ?? null,
      claimPresent, hostClaimPresent, selectedFiles, artifactComplete, journalComplete, capsuleComplete, workerComplete, outcome, lastPhase: last.phase,
      evidenceUploadProven: false, hostLossDurabilityProven: false, ...FLAGS });
    fence.verify(source); checkChannel(); assert.deepEqual(fs.readdirSync(channel).sort(), channelNames); checks.forEach(check => check());
    assert.equal(path.resolve(output), output); assert.equal(fs.existsSync(output), false);
    for (const forbidden of [channel, plan.directory, claim, hostClaim]) assert.ok(output !== forbidden && !output.startsWith(forbidden + path.sep));
    const parentCheck = directoryGuard(path.dirname(output)); parentCheck();
    fs.mkdirSync(output, { mode: 0o700 });
    const manifest = { version: 1, outcome, files: [...collected].map(([name, bytes]) => ({ name, bytes: bytes.length, sha256: hash(bytes) })), ...FLAGS };
    json("manifest.json", manifest);
    for (const [relative, bytes] of collected) {
      const file = path.join(output, relative); fs.mkdirSync(path.dirname(file), { recursive: true, mode: 0o700 });
      const fd = fs.openSync(file, fs.constants.O_WRONLY | fs.constants.O_CREAT | fs.constants.O_EXCL | fs.constants.O_NOFOLLOW, 0o600);
      try { fs.writeFileSync(fd, bytes); fs.fsyncSync(fd); } finally { fs.closeSync(fd); }
      assert.equal(hash(readBounded(file, 32 * 1024 * 1024)), hash(bytes));
    }
    const directories = new Set([path.dirname(output), output]);
    for (const name of collected.keys()) { let d = path.dirname(path.join(output, name)); while (d !== output) { directories.add(d); d = path.dirname(d); } }
    for (const d of [...directories].sort((a, b) => b.length - a.length)) { const fd = fs.openSync(d, fs.constants.O_RDONLY | fs.constants.O_DIRECTORY | fs.constants.O_NOFOLLOW); try { fs.fsyncSync(fd); } finally { fs.closeSync(fd); } }
    parentCheck(); return { outcome, fileCount: collected.size, evidenceUploadProven: false, hostLossDurabilityProven: false, ...FLAGS };
  } catch { throw new Error("Order evidence export failed; preserve local attempt; no retry"); }
}
if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try { assert.equal(process.argv.length, 4); const result = await collectOrderHandoffEvidence({ channel: process.argv[2], output: process.argv[3] });
    process.stdout.write(JSON.stringify(result) + "\n"); if (result.outcome !== "passed") process.exitCode = 1;
  } catch { process.stderr.write("Order evidence export failed; preserve local attempt; no retry\n"); process.exitCode = 1; }
}
